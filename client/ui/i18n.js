function tr(key, vars) {
  const text = STRINGS[LANG][key] ?? STRINGS.ru[key] ?? key;
  return vars ? text.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? "") : text;
}

// on startup and on language change
function applyStaticTexts() {
  document.documentElement.lang = LANG;
  for (const el of document.querySelectorAll("[data-i18n]")) el.textContent = tr(el.dataset.i18n);
  for (const el of document.querySelectorAll("[data-i18n-html]")) el.innerHTML = tr(el.dataset.i18nHtml);
  for (const el of document.querySelectorAll("[data-i18n-placeholder]")) el.placeholder = tr(el.dataset.i18nPlaceholder);
  for (const el of document.querySelectorAll("[data-i18n-title]")) el.title = tr(el.dataset.i18nTitle);
}
